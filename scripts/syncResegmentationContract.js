'use strict';

// Keep deployment independent of the sibling Web checkout. The checked-in
// copy has one canonical source and a deterministic drift check, no runtime
// dependency on the local workspace layout or a second hand-written validator.
const fs = require('fs');
const path = require('path');
const source = path.resolve(
  __dirname,
  '../../cboard/src/common/communicationSupport/resegmentationContract.js'
);
const target = path.resolve(__dirname, '../api/helpers/resegmentationContract.js');
const names = [
  'RESEGMENT_CONTRACT_VERSION',
  'MAX_RESEGMENT_SOURCE_LENGTH',
  'validateResegmentSource',
  'readResegmentTokens',
  'normalizeResegmentResponse'
];
const generated =
  "'use strict';\n// Generated by scripts/syncResegmentationContract.js; do not edit.\n" +
  fs.readFileSync(source, 'utf8').replace(/^export /gm, '') +
  '\nmodule.exports = { ' + names.join(', ') + ' };\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== generated) {
    throw new Error('Resegmentation contract drift: run syncResegmentationContract.js');
  }
  console.log('Resegmentation contract copies match');
} else {
  fs.writeFileSync(target, generated);
}
